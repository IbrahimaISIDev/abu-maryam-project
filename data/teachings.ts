export function getTeachingById(id: string): Teaching | undefined {
  return teachings.find((t) => t.id === id);
}

export function getSeriesEpisodes(seriesId: string): Teaching[] {
  return teachings
    .filter((t) => t.seriesId === seriesId)
    .sort((a, b) => (a.episodeNumber ?? 0) - (b.episodeNumber ?? 0));
}

export function getRelatedTeachings(teaching: Teaching, limit = 4): Teaching[] {
  return teachings
    .filter((t) => t.id !== teaching.id && t.theme === teaching.theme)
    .slice(0, limit);
}
